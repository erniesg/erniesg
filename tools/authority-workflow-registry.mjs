import { createHash } from 'node:crypto'
import { lstat, readFile, readdir, realpath } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const AUTHORITY_WORKFLOW_REGISTRY_SCHEMA_VERSION = 1

export const GENERATED_WORKFLOW_MARKER = 'Generated by rucksack'

export const DEFAULT_REGISTRY_PATH = '.agent/authority-workflows.json'

export const WORKFLOW_DIRECTORY = '.github/workflows'

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function countLines(text) {
  if (text === '') return 0
  let lineBreaks = 0
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index]
    if (character === '\r') {
      if (text[index + 1] === '\n') index += 1
      lineBreaks += 1
    } else if (character === '\n') {
      lineBreaks += 1
    }
  }
  const terminated = text.endsWith('\n') || text.endsWith('\r')
  return terminated ? lineBreaks : lineBreaks + 1
}

function finding(code, path, message, severity = 'error') {
  return { code, path, message, severity }
}

function isPositiveInteger(value) {
  return Number.isInteger(value) && value > 0
}

function isNonEmptyString(value) {
  return typeof value === 'string' && value.length > 0
}

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function isStringArray(value) {
  return (
    Array.isArray(value) &&
    value.every((item) => typeof item === 'string' && item.length > 0)
  )
}

function hasPermissionShape(value) {
  return isRecord(value) && isRecord(value.top_level) && isRecord(value.jobs)
}

/**
 * The generator marker must be recognized inside the leading YAML preamble
 * (blank lines, `---` document markers, and comments), so formatting a
 * generated workflow cannot disguise it as handwritten.
 */
export function declaresGeneratorMarker(content) {
  for (const line of content.split('\n')) {
    const trimmed = line.trim()
    if (trimmed === '' || trimmed === '---' || trimmed.startsWith('#')) {
      if (line.includes(GENERATED_WORKFLOW_MARKER)) return true
      continue
    }
    break
  }
  return false
}

export async function loadAuthorityWorkflowRegistry(registryPath) {
  const raw = await readFile(registryPath, 'utf8')
  try {
    return JSON.parse(raw)
  } catch (error) {
    throw new Error(
      `authority-workflow registry is not valid JSON: ${error.message}`,
    )
  }
}

export function validateAuthorityWorkflowRegistry(registry) {
  const findings = []
  if (!isRecord(registry)) {
    return [
      finding(
        'registry-malformed',
        DEFAULT_REGISTRY_PATH,
        'registry must be a JSON object',
      ),
    ]
  }
  if (registry.schema_version !== AUTHORITY_WORKFLOW_REGISTRY_SCHEMA_VERSION) {
    findings.push(
      finding(
        'registry-schema-version',
        DEFAULT_REGISTRY_PATH,
        `expected schema_version ${AUTHORITY_WORKFLOW_REGISTRY_SCHEMA_VERSION}`,
      ),
    )
  }
  if (!isNonEmptyString(registry.owner)) {
    findings.push(
      finding(
        'registry-owner',
        DEFAULT_REGISTRY_PATH,
        'registry must declare a non-empty owner',
      ),
    )
  }
  const generator = registry.generator
  if (
    !isRecord(generator) ||
    !isNonEmptyString(generator.tool) ||
    !isNonEmptyString(generator.package) ||
    !isNonEmptyString(generator.version) ||
    generator.marker !== GENERATED_WORKFLOW_MARKER
  ) {
    findings.push(
      finding(
        'registry-generator',
        DEFAULT_REGISTRY_PATH,
        `registry generator must carry non-empty tool, package, and version plus marker ${GENERATED_WORKFLOW_MARKER}`,
      ),
    )
  }
  const threshold = registry.entry_gate?.loc_threshold
  if (!isPositiveInteger(threshold)) {
    findings.push(
      finding(
        'registry-threshold',
        DEFAULT_REGISTRY_PATH,
        'entry_gate.loc_threshold must be a positive integer',
      ),
    )
  }
  if (!Array.isArray(registry.workflows) || registry.workflows.length === 0) {
    findings.push(
      finding(
        'registry-workflows',
        DEFAULT_REGISTRY_PATH,
        'workflows must be a non-empty array',
      ),
    )
    return findings
  }
  const seen = new Set()
  for (const entry of registry.workflows) {
    const path = entry?.path
    if (
      typeof path !== 'string' ||
      !path.startsWith(`${WORKFLOW_DIRECTORY}/`)
    ) {
      findings.push(
        finding(
          'registry-entry-path',
          DEFAULT_REGISTRY_PATH,
          `invalid workflow path: ${String(path)}`,
        ),
      )
      continue
    }
    if (seen.has(path)) {
      findings.push(
        finding('registry-duplicate', path, 'duplicate registry entry'),
      )
    }
    seen.add(path)
    if (
      typeof entry.sha256 !== 'string' ||
      !/^[0-9a-f]{64}$/.test(entry.sha256)
    ) {
      findings.push(
        finding(
          'registry-sha',
          path,
          'sha256 must be 64 lowercase hex characters',
        ),
      )
    }
    if (!isPositiveInteger(entry.bytes)) {
      findings.push(
        finding('registry-bytes', path, 'bytes must be a positive integer'),
      )
    }
    if (!isPositiveInteger(entry.lines)) {
      findings.push(
        finding('registry-lines', path, 'lines must be a positive integer'),
      )
    }
    if (typeof entry.authority_bearing !== 'boolean') {
      findings.push(
        finding(
          'registry-authority',
          path,
          'authority_bearing must be a boolean',
        ),
      )
    }
    if (!isNonEmptyString(entry.generated_by)) {
      findings.push(
        finding(
          'registry-generated-by',
          path,
          'generated_by must be a non-empty string',
        ),
      )
    }
    if (!isNonEmptyString(entry.generator_identity)) {
      findings.push(
        finding(
          'registry-generator-identity',
          path,
          'generator_identity must be a non-empty string',
        ),
      )
    }
    if (
      isRecord(entry.reproducibility) &&
      entry.reproducibility.matches_checked_in === false &&
      isNonEmptyString(entry.reproducibility.regenerated_generator) &&
      entry.reproducibility.regenerated_generator === entry.generator_identity
    ) {
      findings.push(
        finding(
          'registry-generator-identity-mismatch',
          path,
          'generator_identity must not name the regenerated_generator when the checked-in bytes fail reproduction; record the historical generator identity or mark it unknown',
        ),
      )
    }
    if (!isNonEmptyString(entry.review_class)) {
      findings.push(
        finding(
          'registry-review-class',
          path,
          'review_class must be a non-empty string',
        ),
      )
    }
    if (!isStringArray(entry.triggers) || entry.triggers.length === 0) {
      findings.push(
        finding(
          'registry-triggers',
          path,
          'triggers must be a non-empty array of non-empty strings',
        ),
      )
    }
    if (!hasPermissionShape(entry.permissions)) {
      findings.push(
        finding(
          'registry-permissions',
          path,
          'permissions must carry object top_level and jobs maps',
        ),
      )
    }
    if (!isStringArray(entry.secrets_referenced)) {
      findings.push(
        finding(
          'registry-secrets',
          path,
          'secrets_referenced must be an array of non-empty strings',
        ),
      )
    }
    if (entry.authority_bearing === true && !isNonEmptyString(entry.owner)) {
      findings.push(
        finding(
          'registry-entry-owner',
          path,
          'authority-bearing workflow must declare an owner',
        ),
      )
    }
    if (entry.size_exception !== undefined) {
      const exception = entry.size_exception
      if (
        !isRecord(exception) ||
        !isPositiveInteger(exception.loc_threshold) ||
        !isPositiveInteger(exception.lines) ||
        !isNonEmptyString(exception.authorized_by) ||
        !isNonEmptyString(exception.reason)
      ) {
        findings.push(
          finding(
            'registry-size-exception',
            path,
            'size_exception must carry integer loc_threshold and lines plus non-empty authorized_by and reason',
          ),
        )
      } else {
        if (
          isPositiveInteger(threshold) &&
          exception.loc_threshold !== threshold
        ) {
          findings.push(
            finding(
              'registry-size-exception-threshold',
              path,
              `size_exception.loc_threshold ${exception.loc_threshold} must equal the registered entry_gate.loc_threshold ${threshold}`,
            ),
          )
        }
        if (isPositiveInteger(entry.lines) && exception.lines !== entry.lines) {
          findings.push(
            finding(
              'registry-size-exception-lines',
              path,
              `size_exception.lines ${exception.lines} must equal the registered line count ${entry.lines}`,
            ),
          )
        }
      }
    }
  }
  return findings
}

async function workflowFileNames(workflowDirectory) {
  const names = await readdir(workflowDirectory)
  return names
    .filter((name) => name.endsWith('.yml') || name.endsWith('.yaml'))
    .sort()
}

export async function auditAuthorityWorkflows({ repoRoot, registryPath } = {}) {
  const root = repoRoot ?? process.cwd()
  const resolvedRegistryPath = registryPath ?? join(root, DEFAULT_REGISTRY_PATH)
  const registry = await loadAuthorityWorkflowRegistry(resolvedRegistryPath)
  const validationFindings = validateAuthorityWorkflowRegistry(registry)
  if (validationFindings.length > 0) {
    return { ok: false, findings: validationFindings }
  }
  const findings = []
  const threshold = registry.entry_gate.loc_threshold
  const workflowDirectory = join(root, WORKFLOW_DIRECTORY)
  let directoryStats
  try {
    directoryStats = await lstat(workflowDirectory)
  } catch (error) {
    findings.push(
      finding(
        'workflow-directory-missing',
        WORKFLOW_DIRECTORY,
        String(error.message),
      ),
    )
    return { ok: false, findings }
  }
  if (!directoryStats.isDirectory()) {
    findings.push(
      finding(
        'workflow-directory-not-regular',
        WORKFLOW_DIRECTORY,
        'the workflow directory must be a real directory, not a symlink',
      ),
    )
    return { ok: false, findings }
  }
  const repositoryRootReal = await realpath(root)
  const workflowDirectoryReal = await realpath(workflowDirectory)
  if (workflowDirectoryReal !== join(repositoryRootReal, WORKFLOW_DIRECTORY)) {
    findings.push(
      finding(
        'workflow-directory-not-canonical',
        WORKFLOW_DIRECTORY,
        `the workflow directory resolves outside the canonical repository tree (${workflowDirectoryReal}); symlinked ancestors are not accepted`,
      ),
    )
    return { ok: false, findings }
  }
  const names = await workflowFileNames(workflowDirectory)
  const registered = new Map(
    registry.workflows.map((entry) => [entry.path, entry]),
  )
  const encountered = new Set()
  for (const name of names) {
    const relativePath = `${WORKFLOW_DIRECTORY}/${name}`
    encountered.add(relativePath)
    const absolute = join(workflowDirectory, name)
    let stats
    try {
      stats = await lstat(absolute)
    } catch (error) {
      findings.push(
        finding('workflow-unreadable', relativePath, String(error.message)),
      )
      continue
    }
    if (!stats.isFile()) {
      findings.push(
        finding(
          'workflow-not-regular-file',
          relativePath,
          'registered or generated workflows must be regular files, not symlinks or directories',
        ),
      )
      continue
    }
    const buffer = await readFile(absolute)
    const content = buffer.toString('utf8')
    const isGenerated = declaresGeneratorMarker(content)
    const entry = registered.get(relativePath)
    if (entry === undefined) {
      findings.push(
        finding(
          isGenerated
            ? 'unregistered-generated-workflow'
            : 'unregistered-workflow',
          relativePath,
          isGenerated
            ? 'rucksack-generated workflow is absent from the authority registry and must be registered after review'
            : 'workflow is absent from the authority registry; every workflow must be classified and registered centrally',
        ),
      )
      continue
    }
    const digest = sha256(buffer)
    const bytes = buffer.byteLength
    const lines = countLines(content)
    if (entry.sha256 !== digest) {
      findings.push(
        finding(
          'workflow-digest-drift',
          relativePath,
          `sha256 drift: registry has ${entry.sha256} but the file hashes to ${digest}; re-register after review`,
        ),
      )
    }
    if (entry.bytes !== bytes) {
      findings.push(
        finding(
          'workflow-bytes-drift',
          relativePath,
          `byte size drift: registry has ${entry.bytes} but the file is ${bytes} bytes`,
        ),
      )
    }
    if (entry.lines !== lines) {
      findings.push(
        finding(
          'workflow-lines-drift',
          relativePath,
          `line count drift: registry has ${entry.lines} but the file has ${lines} lines`,
        ),
      )
    }
    if (lines > threshold && entry.size_exception === undefined) {
      findings.push(
        finding(
          'missing-size-exception',
          relativePath,
          `${lines} lines exceeds the ${threshold}-line entry-gate threshold without a registered size exception`,
        ),
      )
    }
  }
  for (const entry of registry.workflows) {
    if (!encountered.has(entry.path)) {
      findings.push(
        finding(
          'registered-workflow-missing',
          entry.path,
          'registry entry has no workflow file under the workflow directory',
        ),
      )
    }
  }
  const ok = !findings.some((item) => item.severity === 'error')
  return { ok, findings }
}

export async function runAuthorityWorkflowRegistryCli(
  argv = process.argv.slice(2),
) {
  const args = new Map()
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index]
    if (token === '--repo-root' || token === '--registry') {
      args.set(token.slice(2), argv[index + 1])
      index += 1
    }
  }
  const repoRoot = args.get('repo-root') ?? process.cwd()
  const registryPath = args.get('registry') ?? undefined
  const result = await auditAuthorityWorkflows({ repoRoot, registryPath })
  for (const item of result.findings) {
    process.stderr.write(
      `${item.severity}: ${item.code}: ${item.path}: ${item.message}\n`,
    )
  }
  if (result.ok) {
    process.stdout.write('authority-workflow registry audit passed\n')
    return 0
  }
  return 1
}

if (
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1]
) {
  runAuthorityWorkflowRegistryCli()
    .then((code) => {
      process.exitCode = code
    })
    .catch((error) => {
      process.stderr.write(
        `authority-workflow registry audit failed: ${error.message}\n`,
      )
      process.exitCode = 1
    })
}
