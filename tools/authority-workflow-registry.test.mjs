import { createHash } from 'node:crypto'
import { mkdir, mkdtemp, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

import {
  auditAuthorityWorkflows,
  loadAuthorityWorkflowRegistry,
  validateAuthorityWorkflowRegistry,
} from './authority-workflow-registry.mjs'

const GENERATED_HEADER = '# Generated by rucksack.\n'
const HANDWRITTEN_HEADER = '# Maintained by hand.\n'

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function lines(content) {
  return content.endsWith('\n')
    ? content.split('\n').length - 1
    : content.split('\n').length
}

function entryFor(path, content, extra = {}) {
  return {
    path,
    generated_by: 'rucksack',
    generator_identity: 'rucksack-ai-escarp 0.1.7 workflow generator',
    owner: 'erniesg/erniesg',
    authority_bearing: false,
    review_class: 'generated-workflow',
    sha256: sha256(content),
    bytes: Buffer.byteLength(content),
    lines: lines(content),
    triggers: ['workflow_dispatch'],
    permissions: { top_level: {}, jobs: {} },
    secrets_referenced: [],
    ...extra,
  }
}

function registryWith(workflows, locThreshold = 3000) {
  return {
    schema_version: 1,
    owner: 'erniesg/erniesg',
    generator: {
      tool: 'rucksack',
      package: 'rucksack-ai-escarp',
      version: '0.1.7',
      marker: 'Generated by rucksack',
    },
    entry_gate: { loc_threshold: locThreshold },
    workflows,
  }
}

async function makeRepo({ workflows, registry, symlinks = {} }) {
  const root = await mkdtemp(join(tmpdir(), 'authority-workflow-'))
  await mkdir(join(root, '.github/workflows'), { recursive: true })
  await mkdir(join(root, '.agent'), { recursive: true })
  for (const [name, content] of Object.entries(workflows)) {
    await writeFile(join(root, '.github/workflows', name), content)
  }
  for (const [name, target] of Object.entries(symlinks)) {
    await symlink(target, join(root, '.github/workflows', name))
  }
  await writeFile(
    join(root, '.agent/authority-workflows.json'),
    JSON.stringify(registry, null, 2),
  )
  return root
}

function codes(findings) {
  return findings.map((item) => item.code)
}

describe('authority workflow registry', () => {
  it('registers every rucksack-generated workflow and audits this repository clean', async () => {
    const result = await auditAuthorityWorkflows({ repoRoot: process.cwd() })
    expect(result.findings).toEqual([])
    expect(result.ok).toBe(true)
  })

  it('classifies the evidence publisher as frozen-legacy with a size exception and drift evidence', async () => {
    const registry = await loadAuthorityWorkflowRegistry(
      join(process.cwd(), '.agent/authority-workflows.json'),
    )
    const publisher = registry.workflows.find(
      (entry) =>
        entry.path === '.github/workflows/agent-evidence-publisher.yml',
    )
    expect(publisher).toBeDefined()
    expect(publisher.authority_bearing).toBe(true)
    expect(publisher.classification).toBe('frozen-legacy')
    expect(publisher.size_exception).toMatchObject({
      loc_threshold: 3000,
      authorized_by: '#281',
    })
    expect(publisher.reproducibility.matches_checked_in).toBe(false)
    expect(publisher.reproducibility.regenerated_sha256).not.toBe(
      publisher.sha256,
    )
    expect(typeof publisher.owner).toBe('string')
    expect(typeof publisher.review_class).toBe('string')
  })

  it('fails closed on a rucksack-generated workflow missing from the registry', async () => {
    const handwritten = `${HANDWRITTEN_HEADER}name: hand\n`
    const generated = `${GENERATED_HEADER}name: generated\n`
    const root = await makeRepo({
      workflows: { 'hand.yml': handwritten, 'generated.yml': generated },
      registry: registryWith([
        entryFor('.github/workflows/hand.yml', handwritten),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('unregistered-generated-workflow')
  })

  it('detects the generator marker inside a YAML preamble', async () => {
    const handwritten = `${HANDWRITTEN_HEADER}name: hand\n`
    const generated = `---\n${GENERATED_HEADER}name: generated\n`
    const root = await makeRepo({
      workflows: { 'hand.yml': handwritten, 'generated.yml': generated },
      registry: registryWith([
        entryFor('.github/workflows/hand.yml', handwritten),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('unregistered-generated-workflow')
  })

  it('fails closed on digest drift for a registered workflow', async () => {
    const content = `${GENERATED_HEADER}name: drifted\n`
    const root = await makeRepo({
      workflows: { 'drifted.yml': content },
      registry: registryWith([
        entryFor('.github/workflows/drifted.yml', content, {
          sha256: '0'.repeat(64),
        }),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('workflow-digest-drift')
  })

  it('counts a final unterminated workflow line', async () => {
    const content = `${GENERATED_HEADER}name: unterminated`
    const root = await makeRepo({
      workflows: { 'unterminated.yml': content },
      registry: registryWith([
        entryFor('.github/workflows/unterminated.yml', content),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(codes(result.findings)).not.toContain('workflow-lines-drift')
    expect(result.ok).toBe(true)
  })

  it('fails closed when a registered workflow disappears', async () => {
    const content = `${GENERATED_HEADER}name: present\n`
    const root = await makeRepo({
      workflows: { 'present.yml': content },
      registry: registryWith([
        entryFor('.github/workflows/present.yml', content),
        entryFor(
          '.github/workflows/gone.yml',
          `${GENERATED_HEADER}name: gone\n`,
        ),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('registered-workflow-missing')
  })

  it('rejects a symlinked workflow entry', async () => {
    const content = `${GENERATED_HEADER}name: linked\n`
    const root = await mkdtemp(join(tmpdir(), 'authority-workflow-'))
    await mkdir(join(root, '.github/workflows'), { recursive: true })
    await mkdir(join(root, '.agent'), { recursive: true })
    await writeFile(join(root, 'target.yml'), content)
    await symlink(
      join(root, 'target.yml'),
      join(root, '.github/workflows/linked.yml'),
    )
    await writeFile(
      join(root, '.agent/authority-workflows.json'),
      JSON.stringify(
        registryWith([entryFor('.github/workflows/linked.yml', content)]),
        null,
        2,
      ),
    )
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('workflow-not-regular-file')
  })

  it('rejects a symlinked workflow directory', async () => {
    const content = `${GENERATED_HEADER}name: linked\n`
    const root = await mkdtemp(join(tmpdir(), 'authority-workflow-'))
    await mkdir(join(root, '.agent'), { recursive: true })
    await mkdir(join(root, '.github'), { recursive: true })
    await mkdir(join(root, 'elsewhere'), { recursive: true })
    await writeFile(join(root, 'elsewhere/linked.yml'), content)
    await symlink(join(root, 'elsewhere'), join(root, '.github/workflows'))
    await writeFile(
      join(root, '.agent/authority-workflows.json'),
      JSON.stringify(
        registryWith([entryFor('.github/workflows/linked.yml', content)]),
        null,
        2,
      ),
    )
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('workflow-directory-not-regular')
  })

  it('rejects attributing frozen bytes to the mismatching generator', () => {
    const content = `${GENERATED_HEADER}name: frozen\n`
    const findings = validateAuthorityWorkflowRegistry(
      registryWith([
        entryFor('.github/workflows/frozen.yml', content, {
          generator_identity: 'rucksack scaffold()',
          reproducibility: {
            matches_checked_in: false,
            regenerated_generator: 'rucksack scaffold()',
          },
        }),
      ]),
    )
    expect(codes(findings)).toContain('registry-generator-identity-mismatch')
  })

  it('fails closed on an unregistered handwritten workflow', async () => {
    const handwritten = `${HANDWRITTEN_HEADER}name: hand\n`
    const registered = `${GENERATED_HEADER}name: ok\n`
    const root = await makeRepo({
      workflows: { 'ok.yml': registered, 'hand.yml': handwritten },
      registry: registryWith([
        entryFor('.github/workflows/ok.yml', registered),
      ]),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('unregistered-workflow')
  })

  it('rejects a symlinked workflow directory ancestor', async () => {
    const content = `${GENERATED_HEADER}name: linked\n`
    const root = await mkdtemp(join(tmpdir(), 'authority-workflow-'))
    await mkdir(join(root, '.agent'), { recursive: true })
    await mkdir(join(root, 'elsewhere/workflows'), { recursive: true })
    await writeFile(join(root, 'elsewhere/workflows/linked.yml'), content)
    await symlink(join(root, 'elsewhere'), join(root, '.github'))
    await writeFile(
      join(root, '.agent/authority-workflows.json'),
      JSON.stringify(
        registryWith([entryFor('.github/workflows/linked.yml', content)]),
        null,
        2,
      ),
    )
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('workflow-directory-not-canonical')
  })

  it('hashes raw bytes before UTF-8 decoding', async () => {
    const original = Buffer.from(`${GENERATED_HEADER}name: \uFFFD\n`, 'utf8')
    const replacement = Buffer.from('\uFFFD', 'utf8')
    const at = original.indexOf(replacement)
    const mutated = Buffer.concat([
      original.subarray(0, at),
      Buffer.from([0x80]),
      original.subarray(at + replacement.length),
    ])
    const root = await mkdtemp(join(tmpdir(), 'authority-workflow-'))
    await mkdir(join(root, '.github/workflows'), { recursive: true })
    await mkdir(join(root, '.agent'), { recursive: true })
    await writeFile(join(root, '.github/workflows/raw.yml'), mutated)
    await writeFile(
      join(root, '.agent/authority-workflows.json'),
      JSON.stringify(
        registryWith([
          entryFor('.github/workflows/raw.yml', original.toString('utf8')),
        ]),
        null,
        2,
      ),
    )
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(codes(result.findings)).toContain('workflow-digest-drift')
  })

  it('counts CR-only line endings in the size gate', async () => {
    const content =
      '# Generated by rucksack.\rname: a\rb: 1\rc: 2\rd: 3\re: 4\rf: 5'
    const root = await makeRepo({
      workflows: { 'cr.yml': content },
      registry: registryWith(
        [entryFor('.github/workflows/cr.yml', content, { lines: 7 })],
        2,
      ),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(codes(result.findings)).not.toContain('workflow-lines-drift')
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('missing-size-exception')
  })

  it('fails closed when an oversized workflow has no size exception', async () => {
    const content = `${GENERATED_HEADER}name: big\na: 1\nb: 2\n`
    const root = await makeRepo({
      workflows: { 'big.yml': content },
      registry: registryWith(
        [entryFor('.github/workflows/big.yml', content)],
        2,
      ),
    })
    const result = await auditAuthorityWorkflows({ repoRoot: root })
    expect(result.ok).toBe(false)
    expect(codes(result.findings)).toContain('missing-size-exception')
  })

  it('binds a size exception to the registered threshold and line count', async () => {
    const content = `${GENERATED_HEADER}name: big\n`
    const findings = validateAuthorityWorkflowRegistry(
      registryWith(
        [
          entryFor('.github/workflows/big.yml', content, {
            lines: 3,
            size_exception: {
              loc_threshold: 2,
              lines: 999,
              authorized_by: '#1',
              reason: 'why',
            },
          }),
        ],
        1000,
      ),
    )
    expect(codes(findings)).toContain('registry-size-exception-threshold')
    expect(codes(findings)).toContain('registry-size-exception-lines')
  })

  it('rejects malformed governance metadata', async () => {
    const content = `${GENERATED_HEADER}name: meta\n`
    const entry = entryFor('.github/workflows/meta.yml', content)
    delete entry.generator_identity
    delete entry.triggers
    delete entry.permissions
    delete entry.secrets_referenced
    const registry = registryWith([entry])
    delete registry.generator
    const findings = validateAuthorityWorkflowRegistry(registry)
    expect(codes(findings)).toContain('registry-generator')
    expect(codes(findings)).toContain('registry-generator-identity')
    expect(codes(findings)).toContain('registry-triggers')
    expect(codes(findings)).toContain('registry-permissions')
    expect(codes(findings)).toContain('registry-secrets')
  })

  it('rejects a malformed registry before reading workflows', () => {
    const findings = validateAuthorityWorkflowRegistry({ schema_version: 99 })
    expect(findings.length).toBeGreaterThan(0)
    expect(codes(findings)).toContain('registry-schema-version')
  })
})
